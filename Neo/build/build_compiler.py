#!/usr/bin/env python3
"""NeoTempleOS compiler build pipeline.

Concatenates preprocessed HolyC compiler .HC files into a single compiler.c,
applies post-processing transforms, and generates the master compilation unit.
"""

import os, sys, subprocess, re

PROJECT = os.path.abspath(os.path.join(os.path.dirname(__file__), '../..'))
COMPILER_SRC = os.path.join(PROJECT, 'Compiler')
TRANSPILER = os.path.join(PROJECT, 'Neo/transpiler')
PREPROC_SCRIPT = os.path.join(TRANSPILER, 'holyc_preprocess.py')
RUNTIME = os.path.join(PROJECT, 'Neo/runtime')
PREPROC = os.path.join(os.path.dirname(__file__), 'preprocessed')
master_path = os.path.join(os.path.dirname(__file__), 'compiler.c')

PRJ_ORDER = [
    'Templates', 'CExts', 'CInit', 'CExcept', 'LexLib', 'Lex',
    'CHash', 'UAsm', 'PrsLib', 'AsmInit', 'AsmLib', 'AsmResolve',
    'Asm', 'OptLib', 'PrsExp', 'PrsVar', 'CMisc', 'CMain', 'PrsStmt',
    'OptPass012', 'OptPass3', 'OptPass4', 'OptPass5', 'OptPass6',
    'BackLib', 'BackFA', 'BackFB', 'BackA', 'BackB', 'BackC',
    'OptPass789A',
]

STUB_FILES = {
    'Templates': 'Templates_stub.c',
    'CMisc': 'CMisc_stub.c',
}

def need_rebuild(rebuild, src, dst):
    if rebuild: return True
    if not os.path.exists(dst): return True
    return os.path.getmtime(src) > os.path.getmtime(dst)

def preprocess_file(name, rebuild=False):
    src = os.path.join(COMPILER_SRC, name + '.HC')
    dst = os.path.join(PREPROC, name + '.c')
    
    # Check if this file should use a stub instead
    if name in STUB_FILES:
        stub_src = os.path.join(os.path.dirname(__file__), STUB_FILES[name])
        if os.path.exists(stub_src):
            if need_rebuild(rebuild, stub_src, dst):
                with open(stub_src) as sf:
                    stub_content = sf.read()
                with open(dst, 'w') as df:
                    df.write(stub_content)
                print(f'  STUB {name}.c (from {STUB_FILES[name]}, {len(stub_content)} bytes)')
            else:
                print(f'  OK  {name}.c (stub cached)')
            return True
        else:
            print(f'  SKIP {name} -- stub file {STUB_FILES[name]} not found')
            return False
    
    if not os.path.exists(src):
        print(f'  SKIP {name}.HC -- not found')
        return False
    
    if not need_rebuild(rebuild, src, dst):
        print(f'  OK  {name}.c (cached)')
        return True
    
    try:
        result = subprocess.run(
            [sys.executable, PREPROC_SCRIPT, src],
            capture_output=True, text=True, check=True
        )
    except subprocess.CalledProcessError as e:
        print(f'  FAIL {name}.HC -- preprocessor error: {e.stderr.strip()}')
        return False
    
    lines = result.stdout.split('\n')
    filtered = [l for l in lines if not l.strip().startswith('#include "holyc_types.h"')]
    
    with open(dst, 'w') as f:
        f.write('\n'.join(filtered))
    
    print(f'  OK  {name}.c ({len(result.stdout)} bytes)')
    return True

def check_brace_balance(content):
    """Count braces to detect imbalance."""
    
    # Remove string literals and comments
    clean = content
    # Remove single-line comments
    clean = re.sub(r'//.*', '', clean)
    # Remove multi-line comments
    clean = re.sub(r'/\*.*?\*/', '', clean, flags=re.DOTALL)
    # Remove string literals (simplistic)
    clean = re.sub(r'"[^"\\]*(?:\\.[^"\\]*)*"', '', clean)
    # Remove char literals
    clean = re.sub(r"'[^'\\]*(?:\\.[^'\\]*)*'", '', clean)
    
    open_count = clean.count('{')
    close_count = clean.count('}')
    return open_count, close_count, open_count - close_count

def generate_master():
    """Generate compiler.c -- the master compilation unit."""
    
    # Collect C files from preprocessor output
    lines = ['/* Auto-generated NeoTempleOS Compiler -- do not edit */']
    lines.append('/* Generated by build_compiler.py */')
    lines.append('')
    lines.append('#include "holyc.h"')
    lines.append('#include "holyc_compiler_types.h"')
    lines.append('')
    lines.append('/* Global declarations from Compiler.PRJ */')
    lines.append('struct CCmpGlbls cmp;')
    lines.append('struct CUAsmGlbls uasm;')
    lines.append('struct CTask *__holyc_fs;')
    lines.append('struct CCPU  *__holyc_gs;')
    lines.append('')
    lines.append('extern I64 ExeCmdLine(struct CCmpCtrl *cc);')
    lines.append('')
    
    # Forward declare ICMov
    lines.append('extern U0 ICMov(CIntermediateCode *tmpi, CICType t1, I64 r1, I64 d1, CICType t2, I64 r2, I64 d2, I64 rip);')
    lines.append('')
    
    lines.append('/* === Preprocessed HolyC compiler source files === */')
    lines.append('')
    
    for i, name in enumerate(PRJ_ORDER):
        src_file = os.path.join(PREPROC, name + '.c')
        if not os.path.exists(src_file):
            print(f'  MISSING {name}.c -- cannot generate master')
            continue
        
        with open(src_file) as f:
            content = f.read()
        
        lines.append(f'/* === {name}.c === */')
        lines.append(content)
        lines.append('')
    
    content = '\n'.join(lines)
    
    # Apply post-processing transforms
    # Fix ICAdd signature to accept void* instead of I64 for arg3
    content = content.replace(
        'I64 opcode_and_precedence, I64 arg, CHashClass *c, I64 flags',
        'I64 opcode_and_precedence, void *arg, CHashClass *c, I64 flags'
    )
    
    # Fix extern template arrays (HolyC __extern labels become C extern decls)
    for tname in ['cmp_templates', 'cmp_templates_dont_pop', 'cmp_templates_dont_push2',
                   'cmp_templates_dont_push', 'cmp_templates_dont_push_pop']:
        content = content.replace(f'extern U32 {tname}[1];', f'extern U8 *{tname}[1];')
    
    # Add headers
    content = content.replace(
        '#include "holyc.h"',
        '#include "holyc.h"\n#include <sys/mman.h>\n#include <unistd.h>'
    )
    
    
    # Make MAlloc results executable for JIT
    content = content.replace(
        '    res=MAlloc(code_size,Fs()->code_heap);',
        '    res=MAlloc(code_size,Fs()->code_heap);\n    if (res) mprotect(res, (code_size+4095)&~4095, PROT_READ|PROT_WRITE|PROT_EXEC);'
    )
    
    # Fix HolyC cast-expressions: *(expr)(Type) -> *((Type)(expr))
    content = re.sub(
        r'\*\(&([A-Za-z_][A-Za-z0-9_]*(?:\s*->\s*[A-Za-z_][A-Za-z0-9_]*)*(?:\s*\[\s*[^\]]+\s*\])+)\)\s*\(\s*(U8|U16|U32|U64|I8|I16|I32|I64|F64)\s*\)',
        r'*((\2*)(&\1))',
        content
    )
    content = re.sub(
        r'([A-Za-z_][A-Za-z0-9_]*(?:\s*->\s*[A-Za-z_][A-Za-z0-9_]*)*(?:\s*\[\s*[^\]]+\s*\])+)\s*\(\s*(I8|I16|I32|I64|U8|U16|U32|U64|F64)\s*\)',
        r'(\2)\1',
        content
    )
    
    # Union access transforms
    content = re.sub(
        r'([A-Za-z_][A-Za-z0-9_]*)\.u32\s*\[\s*([^\]]+)\s*\]',
        r'UNION_U32(\1, \2)',
        content
    )
    content = re.sub(
        r'([A-Za-z_][A-Za-z0-9_]*)\.u16\s*\[\s*([^\]]+)\s*\]',
        r'UNION_U16(\1, \2)',
        content
    )
    content = re.sub(
        r'([A-Za-z_][A-Za-z0-9_]*(?:\s*->\s*[A-Za-z_][A-Za-z0-9_]*)*)\s*->\s*ic_data\.ptr_val',
        r'(CCodeMisc*)UNION_I64(\1->ic_data)',
        content
    )
    
    # Fix ptr arithmetic with pointer subtraction
    content = re.sub(
        r'\(CCodeMisc\*\)UNION_I64\(([^)]+)\)->',
        r'((CCodeMisc*)UNION_I64(\1))->',
        content
    )
    
    # Fix chained ic_cnt/ic_last_start comparison
    # Original: tmpi->((ic_cnt) > (last_start)) && ((last_start) > (tmpi))->ic_last_start
    # Fixed:    tmpi->ic_cnt > last_start && last_start > tmpi->ic_last_start
    content = re.sub(
        r'->\(\(ic_cnt\) > \(last_start\)\) && \(\(last_start\) > \(([^)]+)\)\)->ic_last_start',
        r'->ic_cnt > last_start && last_start > \1->ic_last_start',
        content
    )
    
    # Fix inline Print before string literals
    content = re.sub(
        r'^(\s*)"([^"]*)"\s*\n(\s*Print\()',
        r'\1"\2";\n\3',
        content,
        flags=re.MULTILINE
    )
    
    marker = '/* === Preprocessed HolyC compiler source files === */'
    idx = content.find(marker)
    if idx >= 0:
        before = content[:idx + len(marker)]
        after = content[idx + len(marker):]
        after = re.sub(
            r'extern\s+U0\s+ICMov\s*\([\s\S]*?\)\s*;',
            '',
            after
        )
        content = before + after
    
    # Fix F64 cast assignments to pointer casts
    content = re.sub(
        r'\(F64\)\s*([A-Za-z_][A-Za-z0-9_]*)\s*=',
        r'*(F64*)&\1 =',
        content
    )
    content = re.sub(
        r'\(F64\)\s*([A-Za-z_][A-Za-z0-9_]*(?:\s*->\s*[A-Za-z_][A-Za-z0-9_]*)*)\s*=',
        r'*(F64*)&\1 =',
        content
    )
    
    # Fix I64 cast assignments to pointer casts
    content = re.sub(
        r'\(I64\)\s*([A-Za-z_][A-Za-z0-9_]*)\s*=',
        r'*(I64*)&\1 =',
        content
    )
    
    # Fix modulo/shift on UNION_F64 casts
    content = re.sub(
        r'UNION_F64\(([^)]+)\)\s*%\s*UNION_F64\(([^)]+)\)',
        r'(F64)((I64)UNION_F64(\1)%(I64)UNION_F64(\2))',
        content
    )
    content = re.sub(
        r'UNION_F64\(([^)]+)\)\s*<<\s*UNION_F64\(([^)]+)\)',
        r'(F64)((I64)UNION_F64(\1)<<(I64)UNION_F64(\2))',
        content
    )
    content = re.sub(
        r'UNION_F64\(([^)]+)\)\s*>>\s*UNION_F64\(([^)]+)\)',
        r'(F64)((I64)UNION_F64(\1)>>(I64)UNION_F64(\2))',
        content
    )
    content = re.sub(
        r'UNION_F64\(([^)]+)\)\s*<<\s*([a-zA-Z_][a-zA-Z0-9_]*->[a-zA-Z_][a-zA-Z0-9_]*)\s*;',
        r'(F64)((I64)UNION_F64(\1)<<(I64)(\2));',
        content
    )
    content = re.sub(
        r'UNION_F64\(([^)]+)\)\s*>>\s*([a-zA-Z_][a-zA-Z0-9_]*->[a-zA-Z_][a-zA-Z0-9_]*)\s*;',
        r'(F64)((I64)UNION_F64(\1)>>(I64)(\2));',
        content
    )
    
    # Fix '!' (no-changedown) operator  
    content = content.replace('^^', '^')
    
    # Fix CVI2 struct (self-referential ptr and void member)
    content = content.replace(
        'typedef struct CVI2 {\nCVI2 *next,*last;\n  U0 base;\n} CVI2;',
        'typedef struct CVI2 {\nstruct CVI2 *next,*last;\n  I64 base;\n} CVI2;'
    )

    # Remove bare CInit() call at file scope (handled by holyc_core.c main())
    content = re.sub(r'\nCInit\(\);\n', '\n/* CInit called from main */\n', content)

    # Fix function calls without parentheses (HolyC allows bare names as calls)
    content = re.sub(r'=PrsClassNew;', '=PrsClassNew();', content)
    content = re.sub(r'=CmdLinePmt;', '=CmdLinePmt();', content)

    # Remove duplicate struct typedefs (already in holyc_compiler_types.h)
    for dup in ['CSubSwitch', 'CSwitchCase']:
        # Match: typedef struct NAME {\n...fields...\n} NAME;
        pat = re.compile(
            r'\ntypedef struct ' + dup + r' \{[\s\S]*?\n\} ' + dup + r';'
        )
        content = pat.sub(
            '\n/* ' + dup + ' defined in holyc_compiler_types.h */', content
        )
    
    # Fix hex literal operator precedence: i<<4+ch computes i<<(4+ch) not (i<<4)+ch
    content = content.replace("i<<4+ch-'0'", "(i<<4)+ch-'0'")
    content = content.replace("i<<4+ch-'A'+10", "(i<<4)+ch-'A'+10")
    content = content.replace("i<<4+ch-'a'+10", "(i<<4)+ch-'a'+10")
    content = content.replace("j<<4+ch-'0'", "(j<<4)+ch-'0'")
    content = content.replace("j<<4+ch-'A'+10", "(j<<4)+ch-'A'+10")
    content = content.replace("j<<4+ch-'a'+10", "(j<<4)+ch-'a'+10")

    # Fix operator precedence in data_addr_rip + (dst - *_base)
    content = content.replace(
        'data_addr_rip+dst-*_base',
        'data_addr_rip+(dst-*_base)'
    )
    
    # Fix '*' concatenation with hex constants  
    content = re.sub(
        r'\*0x([0-9A-Fa-f]+)',
        r' * 0x\1',
        content
    )
    
    # Fix '+ -' becoming '+-' which might be confused
    content = content.replace('+ -', '+ -')
    
    for ptrtype in ['U8', 'U16', 'U32', 'I64', 'U64']:
        content = re.sub(
            rf'\*\(\({ptrtype}\*\)(\w+)\)\+\+\s*=\s*([^;]+);',
            rf'*({ptrtype}*)\1 = \2;\1 = (I64)(({ptrtype}*)\1 + 1);',
            content
        )
    for ptrtype in ['U8', 'U16', 'U32', 'I64', 'U64']:
        content = re.sub(
            rf'\*\(\({ptrtype}\*\)(\w+)\)\+\+',
            rf'({{U8 _v=*({ptrtype}*)\1;\1=(I64)(({ptrtype}*)\1+1);_v;}})',
            content
        )
    
    # Fix register offset comparison
    content = re.sub(
        r'reg_offsets\[([^\]]+)\]\s*>\s*0',
        r'reg_offsets[\1].offset > 0',
        content
    )
    
    # Fix pointer subtraction: (i-ptr-1) -> (i - (I64)ptr - 1)
    content = re.sub(
        r'\(\s*([A-Za-z_][A-Za-z0-9_]*)\s*-\s*ptr\s*-\s*([0-9]+)\s*\)',
        r'(\1 - (I64)ptr - \2)',
        content
    )
    content = content.replace('LexExpression2Bin(cc)', 'LexExpression2Bin(cc,NULL)')
    content = re.sub(
        r'i-ptr-(\d+)',
        r'i-(I64)ptr-\1',
        content
    )
    
    # Fix DocWrite forward declaration (conflicts with holyc.h extern U0 DocWrite(CDoc *doc, ...))
    content = content.replace(
        'Bool DocWrite(CDoc *doc,Bool prompt);',
        '/* DocWrite declared in holyc.h */'
    )

    # Disable character echo in LexGetChar (OPTF_ECHO overlaps with WARN_HEADER_MISMATCH)
    content = content.replace(
        'if (cc->opts & OPTF_ECHO &&\n\t  cc->last_U16<256 && Bt(char_bmp_printable,cc->last_U16))\n      Print("%c", cc->last_U16);',
        'if (0 && cc->opts & OPTF_ECHO &&\n\t  cc->last_U16<256 && Bt(char_bmp_printable,cc->last_U16))\n      Print("%c", cc->last_U16); /* echo disabled */'
    )
    
    
    content = re.sub(r'^(\s+)case:\s*$', r'\1case 9:', content, count=1, flags=re.MULTILINE)
    content = re.sub(r'^(\s+)case:\s*$', r'\1case 10:', content, count=1, flags=re.MULTILINE)
    content = re.sub(r'^(\s+)case:\s*$', r'\1case 11:', content, count=1, flags=re.MULTILINE)

    # Fix adam_task -> __holyc_fs (HolyC global for filesystem task)
    content = content.replace('adam_task->', '__holyc_fs->')

    # Fix CAbsCntsI64 union assignments: .abs_cnts=0 -> .abs_cnts.raw=0
    content = re.sub(r'(\w+)->abs_cnts=0', r'\1->abs_cnts.raw=0', content)

    # Fix CAbsCntsI64 & operator: .abs_cnts&1 -> .abs_cnts.raw&1  
    content = re.sub(r'(\w+)->num\.abs_cnts&', r'\1->num.abs_cnts.raw&', content)

    # Fix cur_op.i8[2] -> UNION_I8(cur_op, 2) (I64 treated as union)
    content = content.replace('cur_op.i8[2]', 'UNION_I8(cur_op, 2)')

    # Fix is_template_fun() in variable declarations (C interprets as function decl)
    content = content.replace('is_template_fun();', 'is_template_fun=FALSE;')

    # Fix HashAddAfter with 3 args -> 2 args (C signature only takes (after, entry))
    content = re.sub(r'HashAddAfter\(([^,]+),\s*([^,]+),\s*([^)]+)\)', r'HashAddAfter(\1, \2)', content)

    # Fix *((I32*)rip)++ lvalue pattern
    content = re.sub(r'\*\(\(I32\*\)(\w+)\)\+\+', r'*(I32*)\1;\1=(I64)((I32*)\1+1)', content)
    # Also handle when the result is assigned: disp=*((I32*)rip)++ -> disp=*(I32*)rip; rip+=4;
    content = re.sub(r'(\w+)=\*\(\(I32\*\)(\w+)\)\+\+', r'\1=*(I32*)\2;\2+=4', content)

    # Fix tmpbin->body + ptr & mask operator precedence
    content = re.sub(
        r'_d=tmpbin->body\s*\+\s*(\w+)->rip\s*&\s*\(AOT_BIN_BLK_SIZE-1\)',
        r'_d = (U32 *)(tmpbin->body + (\1->rip & (AOT_BIN_BLK_SIZE-1)))',
        content
    )
    content = re.sub(
        r'_q=tmpbin->body\s*\+\s*(\w+)->rip\s*&\s*\(AOT_BIN_BLK_SIZE-1\)',
        r'_q = (I64 *)(tmpbin->body + (\1->rip & (AOT_BIN_BLK_SIZE-1)))',
        content
    )

    # Fix try/catch blocks: each try without endtry leaves the try macro's
    # wrapping brace open, causing all later functions to be nested.
    # Insert endtry after each catch block's closing brace.
    lines = content.split('\n')
    result = []
    state = 'NORMAL'  # NORMAL, IN_TRY, IN_CATCH
    catch_depth = 0
    brace_depth = 0
    for line in lines:
        stripped = line.strip()
        if state == 'NORMAL' and re.match(r'^\s*try\b', stripped):
            state = 'IN_TRY'
            catch_depth = brace_depth
            result.append(line)
            continue

        if state == 'IN_TRY' and 'catch' in stripped:
            # Transition to IN_CATCH before counting braces on this line
            state = 'IN_CATCH'
            catch_depth = brace_depth  # brace_depth before this line's braces
            # Now count braces (catch's { adds to brace_depth)
            for ch in line:
                if ch == '{': brace_depth += 1
                elif ch == '}': brace_depth -= 1
            result.append(line)
            continue

        if state == 'IN_CATCH':
            for ch in line:
                if ch == '{': brace_depth += 1
                elif ch == '}': brace_depth -= 1
            if brace_depth <= catch_depth:
                # Catch block ended, insert endtry after closing brace
                result.append(line)
                result.append('endtry')
                state = 'NORMAL'
                brace_depth = 0
                catch_depth = 0
                continue
        elif state == 'IN_TRY':
            for ch in line:
                if ch == '{': brace_depth += 1
                elif ch == '}': brace_depth -= 1

        result.append(line)

    content = '\n'.join(result)

    open_count, close_count, diff = check_brace_balance(content)
    print(f'  Brace balance: open={open_count}, close={close_count}, diff={diff}')
    if diff > 0:
        print(f'  Remaining diff={diff} (handled by endtry macros)')
    elif diff < 0:
        content = 'void __holyc_compiler_unit(void) {\n' + content + '\n}'
        print(f'  Wrapped in __holyc_compiler_unit (diff={diff})')
    else:
        print(f'  Brace balance OK')
    
    # Also verify brace balance with ALL preprocessed files combined
    with open(master_path, 'w') as f:
        f.write(content)
    
    print(f'Generated {master_path}')

def main():
    rebuild = '--rebuild' in sys.argv
    
    os.makedirs(PREPROC, exist_ok=True)
    
    print('Preprocessing compiler source files...')
    success = True
    for name in PRJ_ORDER:
        if not preprocess_file(name, rebuild):
            success = False
    
    generate_master()
    
    if not success:
        print('\nWARNING: some files failed to preprocess. Build may fail.')
        sys.exit(1)
    
    print('\nDone. Run "make" to compile.')

if __name__ == '__main__':
    main()
